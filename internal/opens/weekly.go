// weeklyDir holds the weekly summaries, one markdown file per run.
const weeklyDir = "weekly"

// Weekly is what the weekly summary is written from.
type Weekly struct {
	Now  time.Time
	Week time.Duration // the period summarized, ending at Now

	Week7    []SeriesReport // over the week's rows, for capacity
	AllTime  []SeriesReport // over every row, for the wing calibration
	AllWings WingCal        // every series' wing rungs together

	NewSeries []NewSeriesRecord         // detected in the week
	Captured  map[string]int            // captured opens per series, in the week
	Quotes    map[string]NewSeriesQuote // new series' first qualifying quotes
	Titles    map[string]string         // series titles
	BadMakers BadMakers                 // the latest evaluation
	Skips     map[string]int            // skipped opens in the week, by reason
	Captures  struct{ Captures, Markets, Incomplete, Resyncs int }

	Rule QuoteRule

	DataBytes, OpensBytes int64 // under the data directory, and its opens/
	DiskFree, DiskTotal   uint64
	HasDisk               bool
}

// LoadWeekly gathers a Weekly from the opens directory dir (under the
// data directory dataDir) for the week ending at now.
func LoadWeekly(dataDir, dir string, now time.Time, opts Options) (Weekly, error) {
	w := Weekly{Now: now, Week: 7 * 24 * time.Hour, Rule: opts.Rule}
	if w.Rule == (QuoteRule{}) {
		w.Rule = DefaultQuoteRule()
	}
	from := now.Add(-w.Week).UnixMilli()
	in := func(ms int64) bool { return ms >= from && ms <= now.UnixMilli() }

	rows, err := LoadRows(dir)
	if err != nil {
		return w, err
	}
	var week []OpenRow
	for _, r := range rows {
		if in(r.OpenMs) {
			week = append(week, r)
		}
	}
	opts.MinOpens = 1
	w.Week7 = Report(week, opts)
	w.AllTime = Report(rows, opts)
	held := make([]OpenRow, len(rows))
	for i, r := range rows {
		held[i] = applyRule(r, w.Rule)
	}
	w.AllWings = wingCalibrate("all series", held, opts.Seed, max(opts.Resamples, 1), cmp.Or(opts.WingInterval, 0.9))

	if w.Titles, err = SeriesTitles(dir); err != nil {
		return w, err
	}
	news, err := readOptional[NewSeriesRecord](filepath.Join(dir, newSeriesFile))
	if err != nil {
		return w, err
	}
	for _, n := range news {
		if in(n.T) {
			w.NewSeries = append(w.NewSeries, n)
		}
	}
	quotes, err := readOptional[NewSeriesQuote](filepath.Join(dir, newQuotesFile))
	if err != nil {
		return w, err
	}
	w.Quotes = map[string]NewSeriesQuote{}
	for _, q := range quotes {
		if _, ok := w.Quotes[q.Series]; !ok {
			w.Quotes[q.Series] = q
		}
	}
	caps, err := readOptional[CaptureRecord](filepath.Join(dir, capturesFile))
	if err != nil {
		return w, err
	}
	w.Captured = map[string]int{}
	conns := map[string]bool{}
	for _, c := range caps {
		if !in(c.OpenMs) {
			continue
		}
		w.Captured[c.Series]++
		w.Captures.Markets++
		w.Captures.Resyncs += c.Resyncs
		if !c.Complete {
			w.Captures.Incomplete++
		}
		conns[fmt.Sprint(c.Event, c.StartMs)] = true
	}
	w.Captures.Captures = len(conns)
	skips, err := readOptional[SkipRecord](filepath.Join(dir, skipsFile))
	if err != nil {
		return w, err
	}
	w.Skips = map[string]int{}
	for _, s := range skips {
		if in(s.T) {
			w.Skips[s.Reason] += s.Markets
		}
	}
	if w.BadMakers, err = LoadBadMakers(dir); err != nil {
		return w, err
	}
	w.DataBytes, w.OpensBytes = dirSize(dataDir), dirSize(dir)
	w.DiskFree, w.DiskTotal, w.HasDisk = diskSpace(dataDir)
	return w, nil
}

func readOptional[T any](path string) ([]T, error) {
	recs, err := storage.ReadJSONL[T](path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("opens: %w", err)
	}
	return recs, nil
}

// dirSize is the total size of the regular files under dir.
func dirSize(dir string) int64 {
	var n int64
	filepath.WalkDir(dir, func(_ string, d fs.DirEntry, err error) error {
		if err == nil && d.Type().IsRegular() {
			if info, err := d.Info(); err == nil {
				n += info.Size()
			}
		}
		return nil
	})
	return n
}

// WeeklyPath is where the summary for the week ending at now goes.
func WeeklyPath(dir string, now time.Time) string {
	return filepath.Join(dir, weeklyDir, now.UTC().Format("2006-01-02")+".md")
}

// WriteWeekly writes the summary as markdown.
func WriteWeekly(out io.Writer, w Weekly) error {
	var b strings.Builder
	day := func(t time.Time) string { return t.UTC().Format("2006-01-02") }
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	title := func(s string) string { return w.Titles[s] }
	p("# Open scanner, week to %s\n\n", day(w.Now))
	p("%s to %s UTC. Quote rule: %v. Generated by `pmde-opens weekly`; see docs/open-scanner.md for every column.\n\n",
		w.Now.Add(-w.Week).UTC().Format("2006-01-02 15:04"), w.Now.UTC().Format("2006-01-02 15:04"), w.Rule)

	// Candidates first: they are what the alert is for.
	p("## Bad-maker candidates\n\n")
	if w.BadMakers.EvaluatedMs == 0 {
		p("No evaluation yet (`pmde-opens badmakers` has not run).\n\n")
	} else {
		cands := w.BadMakers.Candidates()
		p("From the evaluation of %s (%s).\n\n", time.UnixMilli(w.BadMakers.EvaluatedMs).UTC().Format("2006-01-02 15:04 UTC"), w.BadMakers.Rule.Thresholds())
		if len(cands) == 0 {
			p("None.\n\n")
		} else {
			p("| Series | Title | Quoted | Capacity/day | One quote | Events | Net edge [lo] | Wings against/expected (top) |\n|---|---|--:|--:|---|--:|--:|--:|\n")
			for _, e := range cands {
				name := e.Series
				if e.Test {
					name += " (delivery test)"
				}
				p("| %s | %s | %.0f%% of %d | %.0f | %.0f%%: %s x %s, %d bps | %d | %.0f [%.0f] | %d / %.1f (%.1f) |\n",
					name, e.Title, e.QuotedShare*100, e.CaptureOpens, e.MedianCapacity, e.ComboShare*100,
					centi(e.ComboBidSz), centi(e.ComboAskSz), e.ComboSpreadBps, e.SettledEvents,
					e.NetEdgeBps, e.NetEdgeLoBps, e.WingAgainst, e.WingExpected, e.WingHi)
			}
			p("\n")
		}
	}

	p("## Top 10 series by capacity\n\n")
	top := slices.Clone(w.Week7)
	top = slices.DeleteFunc(top, func(r SeriesReport) bool { return r.CapDays == 0 })
	slices.SortStableFunc(top, func(a, c SeriesReport) int {
		return cmp.Or(cmp.Compare(c.Contracts, a.Contracts), cmp.Compare(a.Series, c.Series))
	})
	if len(top) == 0 {
		p("No captured opens this week.\n\n")
	} else {
		p("Median daily contracts (and dollars at risk) on qualifying opening quotes, both sides, all rungs; ntm is a mid of 10-90c.\n\n")
		p("| # | Series | Title | Days | Contracts/day (ntm / wing) | $ at risk/day (ntm / wing) | Quoted / captured | Spread | Traded/day | Quote traded / pulled |\n|--:|---|---|--:|--:|--:|--:|--:|--:|--:|\n")
		for i, r := range top[:min(10, len(top))] {
			flow := "-"
			if r.QuoteFlowOpens > 0 {
				flow = fmt.Sprintf("%.0f%% / %.0f%%", r.TradedShare*100, r.PulledShare*100)
			}
			p("| %d | %s | %s | %d | %.0f (%.0f / %.0f) | %.0f (%.0f / %.0f) | %d / %d | %s | %.0f | %s |\n",
				i+1, r.Series, title(r.Series), r.CapDays, r.Contracts, r.NTMContracts, r.WingContracts,
				r.Dollars, r.NTMDollars, r.WingDollars, r.Captured, r.CaptureOpens,
				na(r.Quoted > 0, "%.0f", r.SpreadBps), r.TradedPerDay, flow)
		}
		p("\n")
	}

	p("## New series this week\n\n")
	if len(w.NewSeries) == 0 {
		p("None detected.\n\n")
	} else {
		p("| Series | Title | Category | Frequency | First seen | Opens captured | Quoted |\n|---|---|---|---|---|--:|---|\n")
		for _, n := range w.NewSeries {
			quoted := "no"
			if q, ok := w.Quotes[n.Ticker]; ok {
				quoted = fmt.Sprintf("yes, %s: %s x %s / %s x %s, %d bps", time.UnixMilli(q.T).UTC().Format("01-02 15:04"),
					cents(q.Bid), centi(q.BidSz), cents(q.Ask), centi(q.AskSz), q.Ask-q.Bid)
			}
			p("| %s | %s | %s | %s | %s | %d | %s |\n", n.Ticker, n.Title, n.Category, n.Frequency,
				time.UnixMilli(n.T).UTC().Format("2006-01-02 15:04"), w.Captured[n.Ticker], quoted)
		}
		p("\n")
	}

	p("## Wing calibration so far\n\n")
	p("Every settled open on record, opening price against result, for rungs whose opening mid was under 10c (low) or over 90c (high). ")
	p("Against: a low rung that resolved yes, or a high one no. Expected is what calibrated quotes would give, with the %.0f%% interval for that count from the event simulation. Events are the sample size.\n\n",
		cmp.Or(w.AllWings.Interval, 0.9)*100)
	p("| Series | Low: rungs (events) | Low: mean mid / yes | High: rungs (events) | High: mean mid / yes | Against / expected | Interval |\n|---|--:|--:|--:|--:|--:|--:|\n")
	row := func(name string, c WingCal) {
		low, high := "-", "-"
		if c.LowN > 0 {
			low = fmt.Sprintf("%.1fc / %.1f%%", c.LowMeanBps/100, c.LowYes*100)
		}
		if c.HighN > 0 {
			high = fmt.Sprintf("%.1fc / %.1f%%", c.HighMeanBps/100, c.HighYes*100)
		}
		flag := ""
		if float64(c.Against) > c.Hi {
			flag = " **above**"
		}
		p("| %s | %d (%d) | %s | %d (%d) | %s | %d / %.1f%s | %.0f-%.0f |\n",
			name, c.LowN, c.LowEvents, low, c.HighN, c.HighEvents, high, c.Against, c.Expected, flag, c.Lo, c.Hi)
	}
	n := 0
	for _, r := range w.AllTime {
		if r.Wing.Events > 0 {
			row(r.Series, r.Wing)
			n++
		}
	}
	if n == 0 {
		p("| (no settled wing rungs yet) | | | | | | |\n")
	} else {
		row("**all series**", w.AllWings)
	}
	p("\n")

	p("## Scanner health\n\n")
	p("| | This week |\n|---|--:|\n")
	p("| Captures (connections) | %d |\n| Markets captured | %d |\n| Captured incompletely | %d |\n| Resyncs during captures | %d |\n",
		w.Captures.Captures, w.Captures.Markets, w.Captures.Incomplete, w.Captures.Resyncs)
	for _, reason := range []string{"concurrency", "late", "vanished"} {
		p("| Skipped opens: %s | %d |\n", reason, w.Skips[reason])
	}
	if w.HasDisk {
		p("| Disk free | %.1f GB of %.1f GB (%.0f%%) |\n", float64(w.DiskFree)/1e9, float64(w.DiskTotal)/1e9, float64(w.DiskFree)/float64(w.DiskTotal)*100)
	} else {
		p("| Disk free | unknown on this OS |\n")
	}
	p("| Data directory | %.1f MB, of which opens/ %.1f MB |\n", float64(w.DataBytes)/1e6, float64(w.OpensBytes)/1e6)
	p("\nSkips are counted from opens/skips.jsonl, captures and resyncs from captures.jsonl, by open time.\n")
	_, err := io.WriteString(out, b.String())
	return err
}
